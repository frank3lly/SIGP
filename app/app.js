    function handleApiStatusUpdate(data) {
      if (!data || !data.cameras) return;
      let updatedAny = false;

      for (const [camId, camData] of Object.entries(data.cameras)) {
        if (!camData.spots) continue;
        camData.spots.forEach(function(sp) {
          const slotId = window.SGIPMapping ? window.SGIPMapping.mapCameraSpotToSlotId(camId, sp.spot_id) : null;
          if (slotId && spotsDatabase[slotId]) {
            const newStatus = sp.occupied ? 'occupied' : 'free';
            const newConf = sp.confidence ? sp.confidence * 100 : 94.0;
            spotsDatabase[slotId].status = newStatus;
            spotsDatabase[slotId].conf = newConf;
            if (camData.battery_percentage !== undefined) {
              spotsDatabase[slotId].battery = camData.battery_percentage;
            }
            updatedAny = true;
          }
        });
      }

      if (updatedAny) {
        applySpotsUpdate();
      }
    }

